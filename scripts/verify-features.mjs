// Run against a local server. Creates one clearly named verification poll and closes it.
import { chromium, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';

(async () => {
  const base = process.env.BASE_URL || 'http://localhost:3000';
  const out = path.resolve('screenshots');
  await fs.mkdir(out, { recursive: true });
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const shot = async (name) => { await page.screenshot({ path: path.join(out, `${name}.png`), fullPage: true, animations: 'disabled' }); };
  const nav = async (label) => { await page.getByRole('navigation').getByRole('button', { name: label, exact: true }).click(); };
  let pollId;
  let identity;
  try {
    await page.goto(base);
    await expect(page.getByRole('heading', { name: 'Kealvi', exact: true })).toBeVisible();
    await page.getByPlaceholder('Anonymous').fill('Kealvi QA');
    await shot('01-overview');
    await nav('Polls');
    await page.getByRole('button', { name: 'Team check-in', exact: true }).click();
    await expect(page.getByPlaceholder('What should we prioritize next?')).toHaveValue('How is the team feeling this week?');
    await shot('02-poll-templates');
    const title = `Workspace verification • ${new Date().toISOString()}`;
    await page.getByPlaceholder('What should we prioritize next?').fill(title);
    const created = page.waitForResponse((r) => r.url() === `${base}/api/polls` && r.request().method() === 'POST');
    await page.getByRole('button', { name: 'Publish poll', exact: true }).click();
    const response = await created;
    expect(response.status()).toBe(201);
    pollId = (await response.json()).id;
    identity = await page.evaluate(() => localStorage.getItem('kealvi_voter_id'));
    const card = page.locator('.poll-card').filter({ has: page.getByRole('heading', { name: title, exact: true }) });
    await expect(card).toBeVisible({ timeout: 30000 });
    if (await page.getByRole('button', { name: 'Hide composer', exact: true }).isVisible()) await page.getByRole('button', { name: 'Hide composer', exact: true }).click();
    await card.getByRole('button', { name: /Energized/ }).click();
    await expect(card.locator('.result-option.selected')).toContainText('Energized', { timeout: 30000 });
    await card.getByRole('button', { name: /Doing well/ }).click();
    await expect(card.locator('.result-option.selected')).toContainText('Doing well', { timeout: 30000 });
    await expect(card.locator('footer')).toContainText('1 total votes');
    await shot('03-live-voting');
    await card.getByRole('button', { name: '☆ Save', exact: true }).click();
    await page.getByRole('button', { name: 'Saved', exact: true }).click();
    await expect(page.locator('.poll-card')).toHaveCount(1);
    await shot('04-saved-polls');
    await card.getByRole('button', { name: 'Copy link', exact: true }).click();
    const link = await page.evaluate(() => navigator.clipboard.readText());
    expect(link).toContain(`poll=${pollId}`);
    const downloadPromise = page.waitForEvent('download');
    await card.getByRole('button', { name: 'Download results', exact: true }).click();
    const download = await downloadPromise;
    const exportPath = path.join(out, 'results-example.json');
    await download.saveAs(exportPath);
    const report = JSON.parse(await fs.readFile(exportPath, 'utf8'));
    expect(report.polls[0].totalVotes).toBe(1);
    expect(report.polls[0]).not.toHaveProperty('creatorId');
    await page.goto(link);
    await page.reload();
    await expect(page.getByText('Viewing a shared poll', { exact: false })).toBeVisible();
    await expect(page.locator('.poll-card')).toHaveCount(1);
    if (await page.getByRole('button', { name: 'Hide composer', exact: true }).isVisible()) await page.getByRole('button', { name: 'Hide composer', exact: true }).click();
    await shot('05-shared-poll');
    await page.getByRole('button', { name: 'Show all polls', exact: true }).click();
    await page.getByRole('button', { name: 'Saved', exact: true }).click();
    await expect(page.locator('.poll-card')).toHaveCount(1);
    await page.getByRole('button', { name: 'My polls', exact: true }).click();
    await expect(page.locator('.poll-card')).toHaveCount(1);
    await shot('06-my-polls');
    await page.getByRole('textbox', { name: 'Search polls', exact: true }).fill('no-match-verification');
    await expect(page.locator('.poll-card')).toHaveCount(0);
    await shot('15-search-empty-state');
    await page.getByRole('textbox', { name: 'Search polls', exact: true }).fill('');
    await page.getByRole('button', { name: 'Voted', exact: true }).click();
    await expect(page.locator('.poll-card')).toHaveCount(1);
    await shot('07-vote-history');
    const denied = await context.request.patch(`${base}/api/polls/${pollId}`, { data: { action: 'close', creatorId: 'unrelated-verification-user' } });
    expect(denied.status()).toBe(403);
    const invalid = await context.request.post(`${base}/api/polls`, { data: { title: 'Invalid deadline check', creatorId: identity, options: ['Yes', 'No'], expiresAt: 'not-a-date' } });
    expect(invalid.status()).toBe(400);
    await card.getByRole('button', { name: 'Close poll', exact: true }).click();
    await expect(card.locator('.poll-meta')).toContainText('Closed', { timeout: 30000 });
    await expect(card.getByRole('button', { name: /Energized/ })).toBeDisabled();
    await shot('08-closed-results');
    const workspace = await (await context.request.get(`${base}/api/polls?voterId=${identity}`)).json();
    const poll = workspace.polls.find((p) => p.id === pollId);
    const closedVote = await context.request.post(`${base}/api/polls/${pollId}/vote`, { data: { optionId: poll.options[0].id, voterId: identity } });
    expect(closedVote.status()).toBe(409);
    for (const [label, file] of [['Leaderboard', '09-leaderboard'], ['Insights', '10-insights'], ['Activity', '11-activity']]) { await nav(label); await shot(file); }
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('.mobile-tabs').getByRole('button', { name: 'Overview', exact: true }).click();
    await shot('12-mobile-overview');
    await page.locator('.mobile-tabs').getByRole('button', { name: 'Polls', exact: true }).click();
    await page.getByRole('button', { name: '+ Create poll', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Start a new poll', exact: true })).toBeVisible();
    await shot('13-mobile-polls');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.locator('.mobile-tabs').getByRole('button', { name: 'Activity', exact: true }).click();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await shot('14-mobile-activity');
    expect(errors).toEqual([]);
    console.log('PASS: templates, create, vote/change, save persistence, share links, export, collections, close ownership, closed voting, validation, desktop/mobile screens.');
    console.log(`Screenshots saved to ${out}`);
  } finally {
    if (pollId && identity) await context.request.patch(`${base}/api/polls/${pollId}`, { data: { action: 'close', creatorId: identity } }).catch(() => {});
    await browser.close();
  }
})().catch((error) => { console.error(error); process.exitCode = 1; });
